"""Exports the original's 80 level shapes (UR-T60) as Assets/StreamingAssets/Settings/shapes.json (UR-T35: the shapes are data Core loads, not C#).

Each shape's outline is the boundary of its sprite's collision mask (alpha > the sprite's tolerance, GameMaker's precise mask; it refuses any shape whose object overrides the mask or whose sprite is not precise), traced pixel
edge by pixel edge, then simplified to within 1.5 px. Coordinates are pixels from the sprite's origin, y up.
Usage: python Tools/export_shapes.py <Ricochet.gmx folder>
"""
import re
import sys
from PIL import Image

KINDS = [("Abstract", "polygon"), ("Triangles", "triangle"), ("Bars", "bar"), ("Circles", "circle"), ("Squares", "square")]


def trace(mask):
    h, w = len(mask), len(mask[0])
    edges = {}
    def on(x, y):
        return 0 <= x < w and 0 <= y < h and mask[y][x]
    for y in range(h):
        for x in range(w):
            if not mask[y][x]:
                continue
            if not on(x, y - 1): edges.setdefault((x, y), []).append((x + 1, y))
            if not on(x + 1, y): edges.setdefault((x + 1, y), []).append((x + 1, y + 1))
            if not on(x, y + 1): edges.setdefault((x + 1, y + 1), []).append((x, y + 1))
            if not on(x - 1, y): edges.setdefault((x, y + 1), []).append((x, y))
    loops = []
    while edges:
        start = next(iter(edges))
        loop, cur = [start], start
        while True:
            nxt = edges[cur].pop()
            if not edges[cur]:
                del edges[cur]
            if nxt == start:
                break
            loop.append(nxt)
            cur = nxt
        loops.append(loop)
    return max(loops, key=lambda l: abs(area(l)))


def area(p):
    return sum(p[i][0] * p[(i + 1) % len(p)][1] - p[(i + 1) % len(p)][0] * p[i][1] for i in range(len(p))) / 2


def rdp(pts, eps):
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = (dx * dx + dy * dy) ** 0.5 or 1
    best, idx = -1, 0
    for i in range(1, len(pts) - 1):
        d = abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / norm
        if d > best:
            best, idx = d, i
    if best <= eps:
        return [pts[0], pts[-1]]
    return rdp(pts[:idx + 1], eps)[:-1] + rdp(pts[idx:], eps)


def simplify(loop, eps=1.5):
    # split the closed loop at its two farthest-apart points so both halves are open curves
    a = 0
    b = max(range(len(loop)), key=lambda i: (loop[i][0] - loop[a][0]) ** 2 + (loop[i][1] - loop[a][1]) ** 2)
    a = max(range(len(loop)), key=lambda i: (loop[i][0] - loop[b][0]) ** 2 + (loop[i][1] - loop[b][1]) ** 2)
    a, b = sorted((a, b))
    first = rdp(loop[a:b + 1], eps)
    second = rdp(loop[b:] + loop[:a + 1], eps)
    return first[:-1] + second[:-1]


def main(root):
    shapes = {}
    for name, prefix in KINDS:
        rows = []
        for i in range(1, 17):
            meta = open("%s/sprites/spr_%s%d.sprite.gmx" % (root, prefix, i)).read()
            ox = int(re.search(r"<xorig>(-?\d+)", meta).group(1))
            oy = int(re.search(r"<yorigin>(-?\d+)", meta).group(1))
            obj = open("%s/objects/obj_%s%d.object.gmx" % (root, prefix, i)).read()
            kind = int(re.search(r"<colkind>(-?\d+)", meta).group(1))
            tolerance = int(re.search(r"<coltolerance>(-?\d+)", meta).group(1))
            if "<maskName>&lt;undefined&gt;</maskName>" not in obj or kind != 0 or tolerance != 0:
                raise SystemExit("obj_%s%d has a mask override, a non-precise collision kind or a tolerance: trace it by hand" % (prefix, i))
            im = Image.open("%s/sprites/images/spr_%s%d_0.png" % (root, prefix, i)).convert("RGBA")
            alpha = im.getchannel("A")
            w, h = im.size
            px = alpha.load()
            mask = [[px[x, y] > tolerance for x in range(w)] for y in range(h)]
            loop = simplify(trace(mask))
            pts = [(x - ox, oy - y) for x, y in loop]
            if area(pts) < 0:
                pts.reverse()
            rows.append([n for p in pts for n in p])
        shapes[name] = rows
    # One outline a line, so a re-export diffs shape by shape. Core's GameData validates the file on load.
    out = ["{",
           '  "_source": "The original\'s 80 level shapes (UR-T60), generated by Tools/export_shapes.py: do not edit by hand. Each outline is x,y pixel pairs from the sprite\'s origin, y up, in a 1920 x 1080 room.",']
    for ki, (name, _) in enumerate(KINDS):
        out.append('  "%s": [' % name)
        rows = shapes[name]
        for i, r in enumerate(rows):
            out.append("    [" + ", ".join(str(n) for n in r) + "]" + ("," if i < len(rows) - 1 else ""))
        out.append("  ]" + ("," if ki < len(KINDS) - 1 else ""))
    out.append("}")
    with open("Assets/StreamingAssets/Settings/shapes.json", "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")


main(sys.argv[1])
